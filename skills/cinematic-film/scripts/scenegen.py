def generate(proj, force=False):
    p = L.paths(proj)
    r = L.Result()
    if not p["storyboard"].exists():
        r.error("no 04_scenes/storyboard.json: run the scenes stage first"); return r
    sb = L.load(p["storyboard"])
    assets = L.load(p["visuals_dir"] / "assets.json", {"assets": {}})["assets"]
    if not assets:
        r.warn("no 05_visuals/assets.json yet: every visual starts as a designed card")
    outline = L.load(p["outline"], {"sections": []})
    topic = L.load(p["topic"], {})
    look = topic.get("look", "wall")
    sec_act = act_of_sections(outline)
    if p["edition"]:
        if sb.get("lang") and sb["lang"] != p["lang"]:
            r.error(f"04_scenes/storyboard.json is the {sb['lang']} edition's; this is {p['lang']}"); return r
        table = edition_table(sb.get("scenes", []), assets, L.load(p["beats"], {}), p["lang"])
        missing = [v["need"] for row in table for v in row["visuals"] if not v["what"]]
        if missing:
            r.error(f"images {', '.join(sorted(set(missing)))} have no {p['lang']} label for their cards (beats.py check)"); return r
    else:
        table = scene_table(sb.get("scenes", []), assets)
    acts = {}
    for row, sc in zip(table, sb.get("scenes", [])):
        acts.setdefault(sec_act.get(row["section"], 1), []).append((row, sc))
    state_p = p["film_dir"] / "acts.json"
    old = {a["act"]: a for a in L.load(state_p, {"acts": []}).get("acts", [])}
    out = []
    for n in sorted(acts):
        rows = [x[0] for x in acts[n]]
        scs = [x[1] for x in acts[n]]
        t0, t1 = scs[0]["start"], scs[-1]["end"] + L.TAIL
        rel = f"06_film/act_{n:02d}/scene.py"
        path = p["proj"] / rel
        text = render_act(n, sb.get("title", ""), look, rows, t0, t1)
        prev_hash = old.get(n, {}).get("hash")
        keep = False
        if path.exists():
            cur = path.read_text()
            edited = not prev_hash or _hash(cur) != prev_hash
            if edited and not force:
                keep = True
                r.warn(f"act {n}: {rel} " + ("has your edits" if prev_hash else "was not written by scenegen") +
                       "; left as it is (--force regenerates it and keeps yours as scene.py.bak)")
            elif edited:
                path.with_suffix(".py.bak").write_text(cur)
        if not keep:
            L.write_text(path, text)
        out.append({"act": n, "scene": rel, "lines": [x["line"] for x in rows], "sections": sorted({x["section"] for x in rows}),
                    "t0": round(t0, 2), "t1": round(t1, 2), "timing": sb.get("timing", "estimate"),
                    "hash": prev_hash if keep else _hash(text)})
    L.save(state_p, {"generated_by": GEN, "look": look, "acts": out} if not p["lang"] else
           {"generated_by": GEN, "lang": p["lang"], "look": look, "acts": out})
    root = p["proj"] / "scene.py"
    if root.exists() and ROOT_MARK not in root.read_text():
        r.warn("scene.py at the project root was not written by scenegen; left as it is. "
               "Render an act with its own file, or move your scene.py aside")
    else:
        L.write_text(root, render_root(out))
    fallback = sum(1 for row in table for v in row["visuals"] if v["status"] not in ("ok", "own"))
    total = sum(len(row["visuals"]) for row in table)
    r.note(f"{len(out)} act(s): " + ", ".join(f"act {a['act']} {len(a['lines'])} lines {L.mmss(a['t0'])}-{L.mmss(a['t1'])}" for a in out))
    if fallback:
        r.warn(f"{fallback} of {total} visuals are designed cards until their images arrive")
    return r


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", required=True)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    r = generate(a.project, a.force)
    print(r.report("scenegen"))
    sys.exit(0 if r.ok else 1)


if __name__ == "__main__":
    main()
